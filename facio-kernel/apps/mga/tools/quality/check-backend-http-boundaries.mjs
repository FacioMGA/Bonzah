#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const SERVER_SRC = path.join(ROOT, 'backend');
const ROUTES_DIR = path.join(SERVER_SRC, 'http', 'routes');
const MODULES_DIR = path.join(SERVER_SRC, 'modules');
const BASELINE_PATH = path.join(
  ROOT,
  'docs',
  'architecture',
  'baselines',
  'backend-http-boundary-baseline.txt',
);
const EXTS = new Set(['.ts', '.tsx', '.js', '.mjs']);
const STRICT = String(process.env.STRICT_BACKEND_HTTP_BOUNDARIES || '') === '1';
const SHOULD_WRITE_BASELINE = process.argv.includes('--write-baseline');

function toPosix(value) {
  return String(value || '').replaceAll('\\', '/');
}

function toRepoRel(absPath) {
  return toPosix(path.relative(ROOT, absPath));
}

function isTestFile(relPath) {
  const p = toPosix(relPath);
  return p.includes('/__tests__/') || p.includes('.test.') || p.includes('.spec.');
}

function walk(dir) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) out.push(...walk(p));
    else if (EXTS.has(path.extname(ent.name))) out.push(p);
  }
  return out;
}

function extractSpecifiers(source) {
  const specs = [];
  const fromRe = /from\s+['"]([^'"]+)['"]/g;
  const dynImportRe = /import\(\s*['"]([^'"]+)['"]\s*\)/g;
  let m;
  while ((m = fromRe.exec(source)) !== null) specs.push(m[1]);
  while ((m = dynImportRe.exec(source)) !== null) specs.push(m[1]);
  return specs;
}

function resolveImportToAbs(fromAbs, specifier) {
  const spec = String(specifier || '');
  if (!spec) return null;
  if (spec.startsWith('.')) return path.resolve(path.dirname(fromAbs), spec);
  if (spec.startsWith('@/backend/')) return path.join(ROOT, spec.replace('@/backend/', 'backend/'));
  if (spec.startsWith('backend/')) return path.join(ROOT, spec);
  return null;
}

function isAllowedHttpRouteTarget(serverRel) {
  const rel = toPosix(serverRel);
  if (!rel.startsWith('backend/')) return true;

  if (rel.startsWith('backend/http/')) return true;

  // Platform is the universal base layer (apps -> domains -> platform); HTTP
  // route composition may always import shared platform infrastructure, e.g.
  // the cross-cutting auth/tenant/rate-limit middleware in
  // backend/platform/http/middleware/.
  if (rel.startsWith('backend/platform/')) return true;

  if (rel.startsWith('backend/modules/')) {
    return rel.includes('/http/') || rel.includes('/app/');
  }

  return false;
}

function collectViolations() {
  const failures = [];

  const routeFiles = walk(ROUTES_DIR);
  for (const fileAbs of routeFiles) {
    const fileRel = toRepoRel(fileAbs);
    if (isTestFile(fileRel)) continue;
    const content = fs.readFileSync(fileAbs, 'utf8');
    for (const spec of extractSpecifiers(content)) {
      const targetAbs = resolveImportToAbs(fileAbs, spec);
      if (!targetAbs) continue;
      const targetRel = toRepoRel(targetAbs);
      if (isAllowedHttpRouteTarget(targetRel)) continue;
      failures.push(`[http-routes-boundary] ${fileRel} -> "${spec}" (${targetRel})`);
    }
  }

  const moduleFiles = walk(MODULES_DIR);
  for (const fileAbs of moduleFiles) {
    const fileRel = toRepoRel(fileAbs);
    if (isTestFile(fileRel)) continue;
    const content = fs.readFileSync(fileAbs, 'utf8');
    for (const spec of extractSpecifiers(content)) {
      const targetAbs = resolveImportToAbs(fileAbs, spec);
      if (!targetAbs) continue;
      const targetRel = toRepoRel(targetAbs);
      if (!targetRel.startsWith('backend/http/')) continue;
      failures.push(`[modules-import-http] ${fileRel} -> "${spec}" (${targetRel})`);
    }
  }

  return Array.from(new Set(failures)).sort();
}

function readBaseline() {
  if (!fs.existsSync(BASELINE_PATH)) return [];
  return fs
    .readFileSync(BASELINE_PATH, 'utf8')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .filter((line) => !line.startsWith('#'));
}

const violations = collectViolations();

if (SHOULD_WRITE_BASELINE) {
  fs.mkdirSync(path.dirname(BASELINE_PATH), { recursive: true });
  fs.writeFileSync(
    BASELINE_PATH,
    [
      '# Backend HTTP boundary baseline',
      '# Auto-generated by tools/quality/check-backend-http-boundaries.mjs --write-baseline',
      '# Format: one violation per line',
      ...violations,
      '',
    ].join('\n'),
  );
  console.log(
    `[backend-http-boundaries] wrote baseline ${toRepoRel(BASELINE_PATH)} (${violations.length} entries)`,
  );
  process.exit(0);
}

const baseline = readBaseline();
const baselineSet = new Set(baseline);
const currentSet = new Set(violations);
const newViolations = violations.filter((line) => !baselineSet.has(line));
const resolvedSinceBaseline = baseline.filter((line) => !currentSet.has(line));

if (STRICT && violations.length > 0) {
  console.error(
    '\n[backend-http-boundaries] STRICT FAILED:\n' +
      violations.map((line) => ` - ${line}`).join('\n') +
      '\n\nUse module http/app boundaries from HTTP routes and remove modules->http imports.\n',
  );
  process.exit(1);
}

if (newViolations.length > 0) {
  console.error(
    '\n[backend-http-boundaries] FAILED (new violations):\n' +
      newViolations.map((line) => ` - ${line}`).join('\n') +
      `\n\nBaseline: ${toRepoRel(BASELINE_PATH)}\n`,
  );
  process.exit(1);
}

if (resolvedSinceBaseline.length > 0) {
  console.log(`[backend-http-boundaries] improved (${resolvedSinceBaseline.length} resolved vs baseline)`);
}

console.log(
  `[backend-http-boundaries] ok (current=${violations.length}, baseline=${baseline.length}, strict=${STRICT ? 'on' : 'off'})`,
);
